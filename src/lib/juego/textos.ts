/** El texto en el idioma pedido, con las {variables} puestas. */
export function traducir(idioma: Idioma, es: string, vars?: Record<string, string | number>) {
  const base = idioma === "es" ? es : (DICCIONARIOS[idioma][es] ?? es);
  return vars ? base.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`)) : base;
}
